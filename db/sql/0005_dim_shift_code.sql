-- dbo.dim_shift_code: attendance shift codes (HR) -- replaces data/PLH_Shift_Code_Map.csv [DECISION 19-Nov-2026, Thanh].
-- The engine reads it through sched.vw_engine_shift_code; the API through sched.vw_input_shift_code.
-- * One row per code; (StartTime, EndTime) is matched exactly. EndTime <= StartTime = overnight shift (ends next day).
-- * Several codes for the same (start, end): the lowest SortOrder wins (= first row of the HR file).
-- * The 7 codes Excel stored in scientific notation (11000 -> 11E3, 1100 -> 11E2, 110000 -> 11E4, 1100000 -> 11E5, 11000000 -> 11E6, 110000000 -> 11E7, 110 -> 11E1) are written repaired.
-- Table is created only when missing; seed rows only when the table is empty (re-running never overwrites HR edits).

IF OBJECT_ID(N'dbo.dim_shift_code', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.dim_shift_code (
        ShiftCode      NVARCHAR(20)   NOT NULL CONSTRAINT PK_dim_shift_code PRIMARY KEY,
        StartTime      TIME(0)        NOT NULL,
        EndTime        TIME(0)        NOT NULL,
        DurationHours  DECIMAL(4, 2)  NOT NULL,
        IsOvernight    AS CAST(CASE WHEN EndTime <= StartTime THEN 1 ELSE 0 END AS BIT),
        SortOrder      INT            NOT NULL,
        IsActive       BIT            NOT NULL CONSTRAINT DF_dim_shift_code_IsActive DEFAULT (1),
        Note           NVARCHAR(200)  NULL,
        CreatedAt      DATETIMEOFFSET NOT NULL CONSTRAINT DF_dim_shift_code_CreatedAt DEFAULT (SYSDATETIMEOFFSET()),
        UpdatedAt      DATETIMEOFFSET NOT NULL CONSTRAINT DF_dim_shift_code_UpdatedAt DEFAULT (SYSDATETIMEOFFSET()),
        UpdatedBy      NVARCHAR(256)  NOT NULL CONSTRAINT DF_dim_shift_code_UpdatedBy DEFAULT (N'seed 0005'),
        CONSTRAINT CK_dim_shift_code_Duration CHECK (DurationHours > 0 AND DurationHours <= 24)
    );
    CREATE INDEX IX_dim_shift_code_Times ON dbo.dim_shift_code (StartTime, EndTime, SortOrder);
END
GO

