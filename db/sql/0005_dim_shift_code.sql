-- engine input contract (same columns as the old CSV): start / end 'HH:mm', file order = SortOrder
CREATE VIEW sched.vw_engine_shift_code AS
SELECT ShiftCode AS shift_code, CONVERT(CHAR(5), StartTime, 108) AS start, CONVERT(CHAR(5), EndTime, 108) AS [end],
       DurationHours AS duration_hours, SortOrder AS sort_order
FROM dbo.dim_shift_code
WHERE IsActive = 1;
GO

CREATE VIEW sched.vw_input_shift_code AS
SELECT ShiftCode, CONVERT(CHAR(5), StartTime, 108) AS StartTime, CONVERT(CHAR(5), EndTime, 108) AS EndTime, DurationHours, IsOvernight,
       SortOrder, IsActive, Note, UpdatedBy, CAST(UpdatedAt AT TIME ZONE 'SE Asia Standard Time' AS DATETIME2(0)) AS UpdatedAt
FROM dbo.dim_shift_code;
GO
